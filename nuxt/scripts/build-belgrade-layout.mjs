/**
 * Generate the Belgrade-derived layout stylesheet.
 *
 * Drupal's Layout Builder stores Bootstrap class names in
 * `layout_builder__layout` and serves them over JSON:API as data. Belgrade's
 * own stylesheet never reaches this frontend, so those classes arrive with
 * nothing defining them and an editor's layout choice is silently dropped.
 *
 * Rather than ship Belgrade's 393KB main.css, which would drag the Drupal
 * theme's whole visual identity across, this compiles only the structural
 * utilities the layout data actually uses, from Belgrade's own SCSS. Compiling
 * from source rather than transcribing rules matters for one reason: Belgrade
 * extends Bootstrap's spacing scale to 6, and `pt-6` and `pb-6` are the two
 * most-used classes in this site's layout data. Stock Bootstrap stops at 5, so
 * anything built against upstream would drop them and look like it worked.
 *
 * Colour utilities are deliberately NOT taken from Belgrade. `bg-primary` in
 * the layout data means "make this section the brand colour", not "make it
 * Belgrade blue", so those few classes resolve to the design tokens instead.
 *
 * Regenerate with `npm run css:belgrade`. The output is committed, so a normal
 * build needs neither sass nor the Drupal tree.
 */

import { execFileSync } from 'node:child_process'
import { mkdtempSync, writeFileSync, readFileSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join, resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const belgrade = resolve(root, '../drupal/web/themes/contrib/belgrade')
const out = join(root, 'assets/css/belgrade-layout.css')

// The utility groups the layout data draws on. Anything outside this list is
// not emitted, which is what keeps the file small.
const GROUPS = [
  'margin', 'margin-x', 'margin-y', 'margin-top', 'margin-end', 'margin-bottom', 'margin-start',
  'padding', 'padding-x', 'padding-y', 'padding-top', 'padding-end', 'padding-bottom', 'padding-start',
  'width', 'height', 'text-align', 'display', 'align-items', 'justify-content',
]

const entry = `
@import "global";
@import "bootstrap/scss/utilities";
@import "utilities";
$utilities: map-get-multiple($utilities, (${GROUPS.map((g) => `"${g}"`).join(',')}));
@import "bootstrap/scss/containers";
@import "bootstrap/scss/grid";
@import "bootstrap/scss/utilities/api";
`

const tmp = mkdtempSync(join(tmpdir(), 'belgrade-'))
try {
  writeFileSync(join(tmp, 'entry.scss'), entry)
  execFileSync(
    'npx',
    ['sass', `--load-path=${join(root, 'node_modules')}`, `--load-path=${join(belgrade, 'scss')}`,
      '--style=compressed', '--no-source-map', join(tmp, 'entry.scss'), join(tmp, 'out.css')],
    { stdio: ['ignore', 'ignore', 'inherit'], cwd: root }
  )

  const generated = readFileSync(join(tmp, 'out.css'), 'utf8').trim()

  // Colour and brand utilities, mapped to the design tokens rather than
  // Belgrade's palette. Kept by hand because there are only a few and because
  // the mapping is a design decision, not a mechanical translation.
  const colours = `
.bg-light{background-color:#f7f6f3}
.bg-primary{background-color:#101214}
.bg-secondary{background-color:#f7f6f3}
.text-white{color:#fff}
.text-body{color:#101214}
.text-muted{color:#5b6169}
`.trim()

  const header = `/* Generated by scripts/build-belgrade-layout.mjs. Do not edit.\n` +
    `   Structural utilities compiled from Belgrade's SCSS; colours mapped to design tokens.\n` +
    `   Regenerate: npm run css:belgrade */\n`

  writeFileSync(out, `${header}${generated}\n${colours}\n`)

  const bytes = readFileSync(out).length
  console.log(`Wrote ${out} (${(bytes / 1024).toFixed(1)}KB)`)
} finally {
  rmSync(tmp, { recursive: true, force: true })
}
